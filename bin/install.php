<?php

declare(strict_types=1);

/**
 * DoorLock installer.
 *
 * Writes config/config.local.php, applies database migrations and optionally
 * creates the first administrator. Never prints or stores a default password.
 *
 * Examples:
 *   php bin/install.php --driver=sqlite --sqlite-path=storage/doorlock.sqlite \
 *       --admin-user=admin
 *
 *   php bin/install.php --driver=mysql --db-host=127.0.0.1 --db-name=doorlock \
 *       --db-user=doorlock --db-password='…' --app-url=https://door.example.com \
 *       --admin-user=admin --admin-password='…'
 */

require dirname(__DIR__) . '/includes/bootstrap.php';

use DoorLock\Cli;
use DoorLock\Config;
use DoorLock\ConfigError;
use DoorLock\DatabaseUnavailable;
use DoorLock\Db;
use DoorLock\Migrator;
use DoorLock\Util;
use DoorLock\Validator;

$options = Cli::parse()['options'];
if (isset($options['help'])) {
    Cli::out('Usage: php bin/install.php --driver=mysql|sqlite [options]');
    Cli::out('  --env=production|staging|development');
    Cli::out('  --app-url=https://…');
    Cli::out('  --driver=mysql --db-host=… --db-port=3306 --db-name=… --db-user=… --db-password=…');
    Cli::out('  --driver=sqlite --sqlite-path=storage/doorlock.sqlite');
    Cli::out('  --admin-user=NAME [--admin-password=…] [--admin-role=admin]');
    Cli::out('  --force   overwrite an existing config/config.local.php');
    exit(0);
}

$root = DOORLOCK_ROOT;
$configPath = $root . '/config/config.local.php';
$force = Cli::flag('force');

if (is_file($configPath) && !$force) {
    Cli::err('config/config.local.php already exists. Use --force to replace it.');
    exit(1);
}

$env = Cli::option('env', 'production');
if (!in_array($env, ['production', 'staging', 'development'], true)) {
    Cli::err('--env must be production, staging or development.');
    exit(64);
}

$driver = Cli::option('driver', 'mysql');
if (!in_array($driver, ['mysql', 'sqlite'], true)) {
    Cli::err('--driver must be mysql or sqlite.');
    exit(64);
}

$db = ['driver' => $driver];
if ($driver === 'mysql') {
    $db += [
        'host' => Cli::option('db-host', '127.0.0.1'),
        'port' => (int) Cli::option('db-port', '3306'),
        'name' => Cli::option('db-name', 'doorlock'),
        'user' => Cli::option('db-user', 'doorlock'),
        'password' => Cli::option('db-password', ''),
    ];
    $required = ['pdo_mysql'];
} else {
    $sqlitePath = Cli::option('sqlite-path', $root . '/storage/tmp/doorlock.sqlite');
    if (!str_starts_with($sqlitePath, '/')) {
        $sqlitePath = $root . '/' . $sqlitePath;
    }
    $db['sqlite_path'] = $sqlitePath;
    $required = ['pdo_sqlite'];
}

foreach ($required as $extension) {
    if (!extension_loaded($extension)) {
        Cli::err("The PHP extension {$extension} is required for the selected driver.");
        exit(69);
    }
}

$timezone = Cli::option('timezone', 'Asia/Tehran');
try {
    new DateTimeZone($timezone);
} catch (Throwable) {
    Cli::err('Invalid --timezone value.');
    exit(64);
}

$config = [
    'app_env' => $env,
    'app_timezone' => $timezone,
    'app_key' => bin2hex(random_bytes(32)),
    'app_url' => Cli::option('app-url', 'http://localhost'),
    'trust_proxy' => false,
    'log_dir' => $root . '/storage/logs',
    'log_level' => $env === 'production' ? 'info' : 'debug',
    'session' => [
        'name' => 'doorlock_sid',
        'save_path' => $root . '/storage/tmp/sessions',
        'idle_timeout' => 1800,
        'absolute_timeout' => 28800,
        'cookie_secure' => 'auto',
    ],
    'db' => $db,
    'security' => [
        'require_https_for_devices' => $env === 'production',
        'allow_insecure_device_http' => false,
        'require_https_for_admin' => $env !== 'development',
    ],
];

$dir = dirname($configPath);
if (!is_dir($dir) && !@mkdir($dir, 0750, true) && !is_dir($dir)) {
    Cli::err('Unable to create the config directory.');
    exit(73);
}

$export = var_export($config, true);
$contents = "<?php\n\ndeclare(strict_types=1);\n\n/**\n * Generated by bin/install.php. Do not commit this file.\n */\nreturn " . $export . ";\n";
if (@file_put_contents($configPath, $contents, LOCK_EX) === false) {
    Cli::err('Unable to write config/config.local.php.');
    exit(73);
}
@chmod($configPath, 0600);

// Reload configuration from the file that was just written.
Config::load($configPath);

if ($driver === 'mysql') {
    try {
        $serverDsn = sprintf('mysql:host=%s;port=%d;charset=utf8mb4', $db['host'], (int) $db['port']);
        $server = new PDO($serverDsn, (string) $db['user'], (string) $db['password'], [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_TIMEOUT => 5,
        ]);
        $server->exec(sprintf(
            'CREATE DATABASE IF NOT EXISTS `%s` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci',
            str_replace('`', '', (string) $db['name'])
        ));
        Cli::out('Database exists or was created.');
    } catch (Throwable $e) {
        Cli::err('Could not prepare the MySQL database: ' . $e->getMessage());
        Cli::err('Create it manually and re-run migrations with php bin/migrate.php.');
    }
}

Db::disconnect();
try {
    Db::init();
} catch (DatabaseUnavailable $e) {
    Cli::err('Database connection failed after writing the configuration.');
    exit(69);
}

try {
    $migrator = new Migrator($root);
    $result = $migrator->migrate(false, static fn (string $line) => Cli::out($line));
    Cli::out(sprintf('Migrations: %d applied, %d already present.', count($result['applied']), count($result['skipped'])));
} catch (Throwable $e) {
    Cli::err('Migration failed: ' . $e->getMessage());
    exit(1);
}

$adminUser = Cli::option('admin-user');
$generatedPassword = null;
if ($adminUser !== null && $adminUser !== '') {
    $adminUser = Validator::username($adminUser);
    $adminRole = Validator::role(Cli::option('admin-role', 'admin'));
    $adminPassword = Cli::secret(Cli::option('admin-password'), 'Administrator password: ');
    if ($adminPassword === null || $adminPassword === '') {
        $adminPassword = bin2hex(random_bytes(12));
        $generatedPassword = $adminPassword;
    }
    Validator::password($adminPassword, $adminUser);

    try {
        $now = Util::toDb(Util::utcNow());
        $userId = Db::tx(function () use ($adminUser, $adminPassword, $adminRole, $now): int {
            $id = Db::insert(
                'INSERT INTO web_users (username, password_hash, role, is_active, password_changed_at, created_at, updated_at)
                 VALUES (?, ?, ?, 1, ?, ?, ?)',
                [$adminUser, password_hash($adminPassword, PASSWORD_BCRYPT, ['cost' => 12]), $adminRole, $now, $now, $now]
            );
            \DoorLock\Audit::record('users.create', 'web_user', (string) $id, null, [
                'username' => $adminUser,
                'role' => $adminRole,
                'source' => 'installer',
            ], ['actor_username' => 'installer']);
            return $id;
        });
        Cli::out('Administrator created: ' . $adminUser);
        if ($generatedPassword !== null) {
            Cli::out('Generated password (shown once): ' . $generatedPassword);
        }
    } catch (Throwable $e) {
        Cli::err('Could not create the administrator: ' . $e->getMessage());
        Cli::err('You can retry with: php bin/create-admin.php --username=' . $adminUser);
    }
}

Cli::out('');
Cli::out('Installation complete.');
Cli::out('  config: ' . $configPath);
Cli::out('  driver: ' . $driver);
Cli::out('Next steps:');
Cli::out('  1. Point your web server document root at this directory (public files only).');
Cli::out('  2. Ensure storage/logs and storage/tmp are writable by PHP and not web-accessible.');
Cli::out('  3. Serve the panel over HTTPS and set app_url accordingly.');
Cli::out('  4. Register devices and provision their keys from the Devices page.');
exit(0);
